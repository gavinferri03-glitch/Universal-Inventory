
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import 'inventory_models.dart';

class InventoryInvoicePdf {
  static String _date(DateTime value) {
    final day = value.day.toString().padLeft(2, '0');
    final month = value.month.toString().padLeft(2, '0');
    return '$day/$month/${value.year}';
  }

  static String _money(double value) =>
      'NPR ${value.toStringAsFixed(2)}';

  static pw.Widget _heading(
    String title,
    String number,
    DateTime date,
  ) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          'UNIVERSAL INVENTORY',
          style: pw.TextStyle(
            fontSize: 20,
            fontWeight: pw.FontWeight.bold,
          ),
        ),
        pw.SizedBox(height: 5),
        pw.Text(
          title,
          style: pw.TextStyle(
            fontSize: 15,
            fontWeight: pw.FontWeight.bold,
            color: PdfColors.blue900,
          ),
        ),
        pw.SizedBox(height: 8),
        pw.Text('Reference: $number'),
        pw.Text('Date: ${_date(date)}'),
        pw.Divider(),
      ],
    );
  }

  static pw.Widget _detail(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 3),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.SizedBox(
            width: 125,
            child: pw.Text(
              label,
              style: pw.TextStyle(
                fontWeight: pw.FontWeight.bold,
              ),
            ),
          ),
          pw.Expanded(
            child: pw.Text(value.isEmpty ? '-' : value),
          ),
        ],
      ),
    );
  }

  static pw.Widget _itemsTable({
    required List<String> headings,
    required List<List<String>> rows,
  }) {
    return pw.Table(
      border: pw.TableBorder.all(
        color: PdfColors.grey400,
        width: 0.5,
      ),
      columnWidths: {
        0: const pw.FlexColumnWidth(3),
        1: const pw.FlexColumnWidth(1.5),
        2: const pw.FlexColumnWidth(1),
        3: const pw.FlexColumnWidth(1.5),
        4: const pw.FlexColumnWidth(1.7),
      },
      children: [
        pw.TableRow(
          decoration: const pw.BoxDecoration(
            color: PdfColors.blue100,
          ),
          children: headings.map((value) {
            return pw.Padding(
              padding: const pw.EdgeInsets.all(6),
              child: pw.Text(
                value,
                style: pw.TextStyle(
                  fontWeight: pw.FontWeight.bold,
                  fontSize: 9,
                ),
              ),
            );
          }).toList(),
        ),
        ...rows.map(
          (row) => pw.TableRow(
            children: row.map(
              (value) => pw.Padding(
                padding: const pw.EdgeInsets.all(6),
                child: pw.Text(
                  value,
                  style: const pw.TextStyle(fontSize: 9),
                ),
              ),
            ).toList(),
          ),
        ),
      ],
    );
  }

  static pw.Widget _totals(
    List<MapEntry<String, String>> values,
  ) {
    return pw.Align(
      alignment: pw.Alignment.centerRight,
      child: pw.SizedBox(
        width: 250,
        child: pw.Column(
          children: values.map((entry) {
            return pw.Padding(
              padding: const pw.EdgeInsets.symmetric(vertical: 3),
              child: pw.Row(
                mainAxisAlignment:
                    pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text(entry.key),
                  pw.Text(
                    entry.value,
                    style: pw.TextStyle(
                      fontWeight: pw.FontWeight.bold,
                    ),
                  ),
                ],
              ),
            );
          }).toList(),
        ),
      ),
    );
  }

  static pw.Widget _footer() {
    return pw.Column(
      children: [
        pw.SizedBox(height: 25),
        pw.Divider(),
        pw.Text(
          'Thank you.',
          style: pw.TextStyle(
            fontSize: 11,
            fontWeight: pw.FontWeight.bold,
          ),
        ),
        pw.SizedBox(height: 5),
        pw.Text(
          'Generated by Universal Inventory',
          style: const pw.TextStyle(
            fontSize: 9,
            color: PdfColors.grey700,
          ),
        ),
        pw.SizedBox(height: 22),
        pw.Row(
          mainAxisAlignment:
              pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text('Prepared By: __________________'),
            pw.Text('Authorized Signature: __________________'),
          ],
        ),
      ],
    );
  }

  // ============================================================
  // PURCHASE INVOICE
  // ============================================================

  static pw.Document _purchaseDocument(
    PurchaseOrderRecord order, {
    required String branchName,
  }) {
    final document = pw.Document();

    final rows = order.items.map((item) => [
          item.productName,
          item.sku,
          item.quantity.toString(),
          _money(item.unitCost),
          _money(item.total),
        ]).toList();

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (context) => [
          _heading(
            'PURCHASE INVOICE / STOCK RECEIPT',
            order.purchaseOrderNumber,
            order.date,
          ),
          _detail('Supplier', order.supplierName),
          _detail('Supplier Phone', order.supplierPhone),
          _detail('Supplier Address', order.supplierAddress),
          _detail(
            'Supplier Invoice No.',
            order.supplierInvoiceNumber,
          ),
          _detail('Branch', branchName),
          _detail('Order Status', order.status),
          _detail('Payment Method', order.paymentMethod),
          _detail('Payment Status', order.paymentStatus),
          pw.SizedBox(height: 15),
          pw.Text(
            'PURCHASED ITEMS',
            style: pw.TextStyle(
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.SizedBox(height: 7),
          _itemsTable(
            headings: [
              'Product',
              'SKU',
              'Qty',
              'Unit Cost',
              'Total',
            ],
            rows: rows,
          ),
          pw.SizedBox(height: 12),
          _totals([
            MapEntry('Subtotal', _money(order.subtotal)),
            MapEntry('Discount', _money(order.discount)),
            MapEntry('Tax', _money(order.tax)),
            MapEntry('Grand Total', _money(order.total)),
            MapEntry('Amount Paid', _money(order.amountPaid)),
            MapEntry('Balance Due', _money(order.balanceDue)),
          ]),
          pw.SizedBox(height: 15),
          _detail('Notes', order.notes),
          _footer(),
        ],
      ),
    );

    return document;
  }

  // ============================================================
  // SUPPLIER RETURN INVOICE
  // ============================================================

  static pw.Document _supplierReturnDocument(
    SupplierReturnRecord record, {
    required String branchName,
  }) {
    final document = pw.Document();

    final rows = record.items.map((item) => [
          item.productName,
          item.sku,
          item.quantity.toString(),
          _money(item.unitCost),
          _money(item.total),
        ]).toList();

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (context) => [
          _heading(
            'SUPPLIER RETURN NOTE',
            record.returnNumber,
            record.date,
          ),
          _detail('Supplier', record.supplierName),
          _detail('Supplier Phone', record.supplierPhone),
          _detail(
            'Original Purchase',
            record.originalPurchaseOrderNumber,
          ),
          _detail('Branch', branchName),
          _detail('Reason', record.reason),
          _detail('Settlement Type', record.settlementType),
          pw.SizedBox(height: 15),
          pw.Text(
            'RETURNED ITEMS',
            style: pw.TextStyle(
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.SizedBox(height: 7),
          _itemsTable(
            headings: [
              'Product',
              'SKU',
              'Qty',
              'Unit Cost',
              'Total',
            ],
            rows: rows,
          ),
          pw.SizedBox(height: 12),
          _totals([
            MapEntry('Total Units', record.totalUnits.toString()),
            MapEntry('Return Total', _money(record.total)),
          ]),
          pw.SizedBox(height: 15),
          _detail('Additional Notes', record.notes),
          _footer(),
        ],
      ),
    );

    return document;
  }

  // ============================================================
  // SALES INVOICE
  // ============================================================

  static pw.Document _salesDocument(
    SaleRecord sale, {
    required String branchName,
  }) {
    final document = pw.Document();

    final rows = sale.items.map((item) => [
          item.productName,
          item.sku,
          item.quantity.toString(),
          _money(item.unitPrice),
          _money(item.total),
        ]).toList();

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (context) => [
          _heading(
            'SALES TAX INVOICE',
            sale.invoiceNumber,
            sale.date,
          ),
          _detail('Customer', sale.customerName),
          _detail('Customer Phone', sale.customerPhone),
          _detail('Branch', branchName),
          _detail('Payment Method', sale.paymentMethod),
          _detail('Payment Status', sale.paymentStatus),
          pw.SizedBox(height: 15),
          pw.Text(
            'SOLD ITEMS',
            style: pw.TextStyle(
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.SizedBox(height: 7),
          _itemsTable(
            headings: [
              'Product',
              'SKU',
              'Qty',
              'Unit Price',
              'Total',
            ],
            rows: rows,
          ),
          pw.SizedBox(height: 12),
          _totals([
            MapEntry('Subtotal', _money(sale.subtotal)),
            MapEntry('Discount', _money(sale.discount)),
            MapEntry('Tax', _money(sale.tax)),
            MapEntry('Grand Total', _money(sale.total)),
            MapEntry('Amount Received', _money(sale.amountPaid)),
            MapEntry('Balance Due', _money(sale.balanceDue)),
            if (sale.change > 0)
              MapEntry('Change', _money(sale.change)),
          ]),
          _footer(),
        ],
      ),
    );

    return document;
  }

  // ============================================================
  // CUSTOMER SALES RETURN INVOICE
  // ============================================================

  static pw.Document _salesReturnDocument(
    SalesReturnRecord record, {
    required String branchName,
  }) {
    final document = pw.Document();

    final rows = record.items.map((item) => [
          item.productName,
          item.sku,
          item.quantity.toString(),
          _money(item.unitPrice),
          _money(item.total),
        ]).toList();

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (context) => [
          _heading(
            'CUSTOMER SALES RETURN',
            record.returnNumber,
            record.date,
          ),
          _detail('Customer', record.customerName),
          _detail(
            'Original Sales Invoice',
            record.originalInvoiceNumber,
          ),
          _detail('Branch', branchName),
          _detail('Return Reason', record.reason),
          pw.SizedBox(height: 15),
          pw.Text(
            'RETURNED ITEMS',
            style: pw.TextStyle(
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.SizedBox(height: 7),
          _itemsTable(
            headings: [
              'Product',
              'SKU',
              'Qty',
              'Unit Price',
              'Total',
            ],
            rows: rows,
          ),
          pw.SizedBox(height: 12),
          _totals([
            MapEntry('Returned Units', record.items.fold<int>(
              0,
              (sum, item) => sum + item.quantity,
            ).toString()),
            MapEntry('Return Total', _money(record.total)),
          ]),
          _footer(),
        ],
      ),
    );

    return document;
  }

  // ============================================================
  // PRINT AND SHARE ACTIONS
  // ============================================================

  static Future<void> printPurchaseOrder(
    PurchaseOrderRecord order, {
    required String branchName,
  }) async {
    final document = _purchaseDocument(
      order,
      branchName: branchName,
    );

    await Printing.layoutPdf(
      onLayout: (format) async => document.save(),
      name: '${order.purchaseOrderNumber}.pdf',
    );
  }

  static Future<void> sharePurchaseOrder(
    PurchaseOrderRecord order, {
    required String branchName,
  }) async {
    final document = _purchaseDocument(
      order,
      branchName: branchName,
    );

    await Printing.sharePdf(
      bytes: await document.save(),
      filename: '${order.purchaseOrderNumber}.pdf',
    );
  }

